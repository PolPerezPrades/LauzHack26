import { useEffect, useState } from "react";
import { LEVEL_NAMES, UNITS, registerPhrases } from "../content/curriculum";
import { aiAvailable, getPracticePhrases } from "../lib/ai";
import { currentUnitIndex, todaySeconds, unitProgress, unitStatus } from "../lib/engine";
import type { Profile, Progress } from "../lib/storage";

interface Props {
  profile: Profile;
  progress: Progress;
  onStart: (unitIdx: number) => void;
  onSprint: () => void;
  onProgress: (fn: (p: Progress) => Progress) => void;
  onReset: () => void;
  onProfile: (p: Profile) => void;
}

let autoGenerated = false; // once per page load

export function Home({ profile, progress, onStart, onSprint, onProgress, onReset, onProfile }: Props) {
  const cur = currentUnitIndex(profile, progress);
  const goalSec = profile.goalMin * 60;
  const doneSec = todaySeconds(progress);
  const goalPct = Math.min(1, doneSec / goalSec);
  const [ai, setAi] = useState<boolean | null>(null);
  const [genState, setGenState] = useState<"idle" | "loading" | "done">("idle");
  const [settings, setSettings] = useState(false);

  useEffect(() => { aiAvailable().then(setAi); }, []);

  // Generative AI: once the learner reaches level 3, ask Claude for extra practice phrases built
  // only from signs that have a real WLASL clip (validated server-side and again client-side).
  const reachedL3 = UNITS[cur].level >= 3;
  const generate = async () => {
    setGenState("loading");
    const known = Object.keys(progress.items).filter((id) => id.startsWith("w-"));
    const list = await getPracticePhrases(known, 4, progress.difficulty);
    registerPhrases(list);
    onProgress((p) => ({ ...p, aiPhrases: [...p.aiPhrases, ...list].slice(-24) }));
    setGenState("done");
  };
  useEffect(() => {
    if (ai && reachedL3 && progress.aiPhrases.length < 4 && genState === "idle" && !autoGenerated) {
      autoGenerated = true;
      generate();
    }
  }, [ai, reachedL3]); // eslint-disable-line react-hooks/exhaustive-deps

  return (
    <div className="screen home">
      <header className="topbar">
        <div className="brand">🤟 Signa <span className="muted small">ASL</span></div>
        <div className="stats">
          <span className="stat" title="Racha de días">🔥 {progress.streak}</span>
          <span className="stat" title="Puntos de experiencia">⭐ {progress.xp}</span>
          <button className="stat stat-btn" onClick={() => setSettings(!settings)} title="Ajustes">⚙️</button>
        </div>
      </header>

      {settings && (
        <div className="card settings">
          <h3>Ajustes</h3>
          <div className="row-between">
            <span>Objetivo diario</span>
            <div className="seg">
              {([5, 10, 15] as const).map((g) => (
                <button key={g} className={profile.goalMin === g ? "on" : ""} onClick={() => onProfile({ ...profile, goalMin: g })}>{g} min</button>
              ))}
            </div>
          </div>
          <div className="row-between">
            <span>Ejercicios con cámara</span>
            <button className="chip" onClick={() => onProfile({ ...profile, camera: !profile.camera })}>{profile.camera ? "Activados" : "Desactivados"}</button>
          </div>
          <div className="row-between">
            <span>IA (frases y feedback)</span>
            <span className="muted">{ai === null ? "…" : ai ? "Conectada (Claude)" : "No configurada · usando reglas locales"}</span>
          </div>
          <button className="btn btn-danger" onClick={() => confirm("¿Borrar todo el progreso?") && onReset()}>Reiniciar progreso</button>
        </div>
      )}

      <section className="card goal-card">
        <div className="ring" style={{ ["--p" as string]: goalPct }}>
          <span>{Math.round(goalPct * 100)}%</span>
        </div>
        <div className="goal-text">
          <b>Objetivo de hoy</b>
          <div className="muted">{Math.floor(doneSec / 60)} de {profile.goalMin} min · {progress.today.day ? progress.today.xp : 0} XP hoy</div>
          <div className="muted small">Mejor racha: {progress.bestStreak} días · Nivel de dificultad: {{ easier: "suave", same: "normal", harder: "retador" }[progress.difficulty]}</div>
        </div>
        <button className="btn btn-primary btn-big" onClick={() => onStart(cur)}>
          {doneSec >= goalSec ? "Practicar más" : "Empezar lección"}
        </button>
      </section>

      {profile.camera && (
        <section className="card sprint-card" onClick={onSprint}>
          <div className="sprint-emoji">⚡</div>
          <div>
            <b>Sprint de deletreo</b>
            <div className="muted">Deletrea con la cámara todas las palabras que puedas en 60 s · Récord: {progress.sprintBest}</div>
          </div>
          <span className="chev">›</span>
        </section>
      )}

      {[1, 2, 3].map((lvl) => (
        <section key={lvl} className="level">
          <h3 className="level-title">{LEVEL_NAMES[lvl]}</h3>
          <div className="units">
            {UNITS.map((u, i) => ({ u, i })).filter(({ u }) => u.level === lvl).map(({ u, i }) => {
              const st = unitStatus(i, profile, progress);
              const pct = unitProgress(u, progress);
              const locked = st === "locked" || !u.items.length;
              return (
                <button key={u.id} className={`unit unit-${st}`} disabled={locked} onClick={() => onStart(i)}>
                  <span className="unit-icon">{locked ? "🔒" : st === "done" ? "✅" : u.icon}</span>
                  <span className="unit-body">
                    <b>{u.title}</b>
                    <span className="unit-bar"><span style={{ width: `${pct * 100}%` }} /></span>
                    <span className="muted small">
                      {st === "current" ? "En curso" : st === "skipped" ? "Superado en la prueba · repasar" : st === "done" ? "Completado · repasar" : "Bloqueado"}
                      {" · "}{u.items.length} {u.id === "phrases" ? "frases" : "signos"}
                    </span>
                  </span>
                </button>
              );
            })}
          </div>
          {lvl === 3 && reachedL3 && (
            <div className="muted small ai-note">
              {genState === "loading" ? "✨ Generando frases de práctica con IA…" :
                progress.aiPhrases.length ? `✨ ${progress.aiPhrases.length} frases de práctica generadas por IA (con signos reales de WLASL)` :
                ai === false ? "Configura ANTHROPIC_API_KEY para generar frases de práctica con IA." : ""}
              {ai && genState !== "loading" && <button className="link" onClick={generate}> Generar más</button>}
            </div>
          )}
        </section>
      ))}

      <footer className="sources">
        Vídeos de signos: <a href="https://dxli94.github.io/WLASL/" target="_blank" rel="noreferrer">WLASL</a> (clips de diccionarios ASL; uso académico/no comercial) ·
        Alfabeto: ilustraciones de dominio público (<a href="https://commons.wikimedia.org/wiki/File:Sign_language_A.svg" target="_blank" rel="noreferrer">Wikimedia Commons</a>) ·
        Detección de manos: MediaPipe Hands (en tu navegador)
      </footer>
    </div>
  );
}
